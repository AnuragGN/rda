<h1 class="page-title">Philanthropy & Giving</h1>

<p>The Chicago Community Trust works with individuals, families, businesses, foundations, and trusted financial advisors to build charitable giving plans and transform your generosity into powerful, meaningful impact.</p>

<p>If you are a current DAF (Donor Advised Fund) holder and have access to it, you can log in to view your grant and gift history, submit grant recommendations, contribute to your fund and view fund activities.</p>

<p>For any additional help, contact us at <a href="mailto:info@cct.org" style="color: #5ea9c5;">info@cct.org</a> </p>
